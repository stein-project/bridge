import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;

/**
 * Lists every {@code -D} option of the Bridge in docs/OPTIONS.md, from the Javadoc of the {@code
 * *Options} classes: each Javadoc block that starts with {@code {@code -D...}} becomes one line.
 *
 * <p>The section {@code ## Removed options} at the end of docs/OPTIONS.md is written by hand (the
 * options taken out on purpose): it is kept as it is.
 *
 * <pre>
 *   ./gradlew options        writes docs/OPTIONS.md (OptionsDoc &lt;root&gt;)
 *   ./gradlew optionsCheck   fails if docs/OPTIONS.md is out of date (OptionsDoc &lt;root&gt; --check)
 * </pre>
 */
public final class OptionsDoc {

    private static final String OUT = "docs/OPTIONS.md";
    private static final String REMOVED = "## Removed options";

    private static final Pattern CODE = Pattern.compile("\\{@(?:code|link) ([^}]*)\\}");
    private static final Pattern LEAD = Pattern.compile("^[ \\t]*/?\\*+/?[ \\t]?");
    private static final Pattern TRAIL = Pattern.compile("[ \\t]*\\*/[ \\t]*$");

    private OptionsDoc() {}

    public static void main(String[] args) throws IOException {
        if (args.length < 1) {
            System.err.println("usage: OptionsDoc <bridge root> [--check]");
            System.exit(2);
        }
        Path root = Path.of(args[0]);
        boolean check = args.length > 1 && args[1].equals("--check");
        Path out = root.resolve(OUT);
        String current = Files.isRegularFile(out) ? Files.readString(out) : "";
        String wanted = generate(root) + removedSection(current);
        if (check) {
            if (!wanted.equals(current.replace("\r\n", "\n"))) {
                System.err.println(OUT + " is out of date: run ./gradlew options");
                System.exit(1);
            }
            System.out.println(OUT + " is up to date");
            return;
        }
        Files.createDirectories(out.getParent());
        Files.writeString(out, wanted, StandardCharsets.UTF_8);
        long count = wanted.lines().filter(l -> l.startsWith("- ")).count();
        System.out.println(OUT + ": " + count + " lines");
    }

    /** The hand-written tail, from {@code ## Removed options} to the end; empty without one. */
    private static String removedSection(String current) {
        String text = current.replace("\r\n", "\n");
        int at = text.indexOf("\n" + REMOVED + "\n");
        return at < 0 ? "" : text.substring(at);
    }

    private static String generate(Path root) throws IOException {
        StringBuilder b = new StringBuilder();
        b.append("# Stein Bridge options\n\n");
        b.append(
                "Every `-D` option the Bridge reads, generated by `./gradlew options`"
                        + " (`tools/OptionsDoc.java`) from the `*Options` classes.\n");
        b.append(
                "Pass them to the JVM (`./gradlew runClient -Pstein.jvmArgs=\"-D...\"`). Most are"
                        + " diagnostics, verification modes\n");
        b.append(
                "(`*Check`) or kill switches of single optimizations; players never need them."
                        + " Options taken out on purpose are\n");
        b.append("listed at the end.\n");
        for (Path f : optionClasses(root)) {
            String rel = root.relativize(f).toString().replace('\\', '/');
            String cls = f.getFileName().toString().replace(".java", "");
            String pkg =
                    rel.substring(0, rel.lastIndexOf('/'))
                            .replaceFirst("^src/[a-z]+/java/", "")
                            .replace('/', '.');
            b.append("\n## ").append(cls).append("\n\n");
            b.append('`').append(pkg).append('.').append(cls).append("`\n\n");
            for (String option : options(Files.readAllLines(f))) {
                b.append("- ").append(option).append('\n');
            }
        }
        return b.toString();
    }

    /** Every {@code *Options.java} under src, in path order (VideoOptions is a game screen). */
    private static List<Path> optionClasses(Path root) throws IOException {
        try (Stream<Path> files = Files.walk(root.resolve("src"))) {
            return files.filter(
                            p -> {
                                String n = p.getFileName().toString();
                                return n.endsWith("Options.java") && !n.equals("VideoOptions.java");
                            })
                    .sorted(
                            (a, c) ->
                                    a.toString()
                                            .replace('\\', '/')
                                            .compareTo(c.toString().replace('\\', '/')))
                    .toList();
        }
    }

    /** Each Javadoc block joined into one line, kept when it documents a {@code -D} option. */
    static List<String> options(List<String> lines) {
        List<String> out = new ArrayList<>();
        StringBuilder doc = null;
        for (String line : lines) {
            if (line.contains("/**")) {
                doc = new StringBuilder();
            }
            if (doc == null) {
                continue;
            }
            String text = TRAIL.matcher(LEAD.matcher(line).replaceFirst("")).replaceFirst("");
            doc.append(' ').append(text);
            if (line.contains("*/")) {
                String joined = doc.toString();
                doc = null;
                if (joined.matches("^ *\\{@code -D.*")) {
                    out.add(markdown(joined));
                }
            }
        }
        return out;
    }

    /** {@code {@code x}} and {@code {@link x}} as Markdown code, spaces collapsed. */
    private static String markdown(String doc) {
        Matcher m = CODE.matcher(doc);
        String code = m.replaceAll(r -> Matcher.quoteReplacement("`" + r.group(1) + "`"));
        return code.strip().replaceAll(" {2,}", " ");
    }
}
