#!/usr/bin/env bash
# Lists every -D option of the Bridge, from the Javadoc of the *Options classes, into docs/OPTIONS.md.
#
#   bash tools/options.sh          writes docs/OPTIONS.md
#   bash tools/options.sh --check  fails if docs/OPTIONS.md is out of date (CI)
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"; cd "$ROOT"
OUT=docs/OPTIONS.md

generate() {
  echo "# Stein Bridge options"
  echo
  echo "Every \`-D\` option the Bridge reads, generated by \`tools/options.sh\` from the \`*Options\` classes."
  echo "Pass them to the JVM (\`./gradlew runClient -Pstein.jvmArgs=\"-D...\"\`). Most are diagnostics, verification modes"
  echo "(\`*Check\`) or kill switches of single optimizations; players never need them."
  find src -name '*Options.java' ! -name 'VideoOptions.java' | sort | while read -r f; do
    cls="$(basename "$f" .java)"
    pkg="$(dirname "$f" | sed -E 's#^src/[a-z]+/java/##; s#/#.#g')"
    echo
    echo "## $cls"
    echo
    echo "\`$pkg.$cls\`"
    echo
    # Joins each Javadoc block into one line and keeps those that document a -D option.
    awk '
      /\/\*\*/ { doc = ""; inside = 1 }
      inside {
        line = $0
        sub(/^[ \t]*\/?\*+\/?[ \t]?/, "", line)
        sub(/[ \t]*\*\/[ \t]*$/, "", line)
        doc = doc " " line
      }
      /\*\// { inside = 0; if (doc ~ /^ *\{@code -D/) { gsub(/\{@code ([^}]*)\}/, "`&`", doc);
               gsub(/`\{@code /, "`", doc); gsub(/\}`/, "`", doc); gsub(/\{@link ([^}]*)\}/, "`&`", doc);
               gsub(/`\{@link /, "`", doc); gsub(/^ +| +$/, "", doc); gsub(/  +/, " ", doc); print "- " doc } }
    ' "$f"
  done
}

if [ "${1:-}" = "--check" ]; then
  diff <(generate) "$OUT" > /dev/null || { echo "docs/OPTIONS.md is out of date: run bash tools/options.sh" >&2; exit 1; }
  echo "docs/OPTIONS.md is up to date"
else
  mkdir -p docs
  generate > "$OUT"
  echo "$OUT: $(grep -c '^- ' "$OUT") options"
fi
