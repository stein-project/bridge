# Regenerates patcher/redirects-batch.tsv: a ModelBatch hook before each
# OpenGL method that the game jar calls (list in scan/gl-calls.txt, extracted from the
# jar with javap), plus the capture and draw rules for the model parts.
#
# Two kinds of hook:
#   flush   — draws the pending batch (any GL call: the state change
#             must come after the parts that came before it);
#   restore — draws and undoes the batch's drawing state (VBO bound, arrays
#             enabled), before the calls that use arrays or buffers.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"; cd "$ROOT"

hook_for() {
  case "$1" in
    *Pointer*|*ClientState*|*ClientActiveTexture*|*BindBuffer*|*BufferData*|*BufferSubData*|\
    *DeleteBuffers*|*GenBuffers*|*DrawArrays*|*DrawElements*|*ArrayElement*|*InterleavedArrays*)
      echo restore ;;
    *) echo flush ;;
  esac
}

{
  echo "# Batched drawing of model parts (dev.xavier.stein.bridge.engine.ModelBatch; on unless"
  echo "# -Dsteinbridge.opt.vanillaModelBatch=true). Generated by tools/gen-batch-rules.sh"
  echo "# from scan/gl-calls.txt — do not edit by hand."
  echo "#"
  echo "# Capture: vertices of each face while the ModelRenderer list is compiled (bct.d)."
  printf 'org/lwjgl/opengl/GL11\tglNewList\t(II)V\tglNewList\tdev/xavier/stein/bridge/engine/ModelBatch\t\tbct.d\n'
  printf 'org/lwjgl/opengl/GL11\tglEndList\t()V\tglEndList\tdev/xavier/stein/bridge/engine/ModelBatch\t\tbct.d\n'
  printf 'bfx\tb\t()V\tcaptureQuad\tdev/xavier/stein/bridge/engine/ModelBatch\tbefore\tbbs.a\n'
  echo "# Drawing: the parts' callList (render = a, renderWithRotation = b) goes to the batch."
  printf 'bfl\to\t(I)V\tcallList\tdev/xavier/stein/bridge/engine/ModelBatch\t\tbct.a\n'
  printf 'bfl\to\t(I)V\tcallList\tdev/xavier/stein/bridge/engine/ModelBatch\t\tbct.b\n'
  echo "# gfx/SteinEntityInstancer replaces ModelRenderer.render (bct.a(F)V) everywhere; it forwards to the original when inactive."
  printf 'bct\ta\t(F)V\trender\tdev/xavier/stein/gfx/SteinEntityInstancer\tstatic\n'
  echo "# Before ANY OpenGL call made by the game: flush (or restore, if it uses arrays/buffers)."
  grep -E '^org/lwjgl/opengl/(GL[0-9]+|ARB|EXT)[A-Za-z0-9]*\.' scan/gl-calls.txt | while IFS= read -r c; do
    owner="${c%%.*}"; rest="${c#*.}"; name="${rest%%:*}"; desc="${rest#*:}"
    printf '%s\t%s\t%s\t%s\tdev/xavier/stein/bridge/engine/ModelBatch\tbefore\n' "$owner" "$name" "$desc" "$(hook_for "$name")"
  done
} > patcher/redirects-batch.tsv

TAB="$(printf '\t')"
echo "$(grep -c "${TAB}flush${TAB}.*before\$" patcher/redirects-batch.tsv) flush hooks," \
     "$(grep -c "${TAB}restore${TAB}.*before\$" patcher/redirects-batch.tsv) restore hooks in patcher/redirects-batch.tsv"
