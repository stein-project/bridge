package org.lwjgl.input;

import static org.lwjgl.glfw.GLFW.GLFW_CURSOR;
import static org.lwjgl.glfw.GLFW.GLFW_CURSOR_DISABLED;
import static org.lwjgl.glfw.GLFW.GLFW_CURSOR_NORMAL;
import static org.lwjgl.glfw.GLFW.glfwGetCursorPos;
import static org.lwjgl.glfw.GLFW.glfwSetCursorPos;
import static org.lwjgl.glfw.GLFW.glfwSetInputMode;

import dev.xavier.stein.bridge.core.Input;
import dev.xavier.stein.bridge.core.Win;

/**
 * LWJGL 2 mouse API on top of GLFW.
 *
 * <p>Coordinates follow the LWJGL 2 convention: origin at the bottom left corner, Y growing upward.
 * The conversion happens in {@link Input}.
 */
public final class Mouse {

    /** Movement added by mods (e.g. joystick), summed with the cursor's on the next read. */
    private static int dx;

    private static int dy;

    /**
     * Position requested while the cursor is captured (GLFW window coordinates), applied on
     * release; NaN = none.
     */
    private static double releaseX = Double.NaN;

    private static double releaseY;

    private Mouse() {}

    public static boolean isCreated() {
        return Win.isCreated();
    }

    /** Advances to the next event in the queue. */
    public static boolean next() {
        Win.MouseEvent e = Win.mouseEvents.pollFirst();
        if (e == null) {
            return false;
        }
        Win.currentMouse = e;
        return true;
    }

    public static int getEventButton() {
        return Win.currentMouse.button;
    }

    public static boolean getEventButtonState() {
        return Win.currentMouse.state;
    }

    public static int getEventX() {
        return Win.currentMouse.x;
    }

    public static int getEventY() {
        return Win.currentMouse.y;
    }

    public static int getEventDWheel() {
        return Win.currentMouse.dwheel;
    }

    public static int getX() {
        return Win.mouseX;
    }

    public static int getY() {
        return Win.mouseY;
    }

    /** Accumulator since the last read; reset when read, as in LWJGL 2. */
    public static int getDX() {
        int d = Win.mouseDX + dx;
        Win.mouseDX = 0;
        dx = 0;
        return d;
    }

    public static int getDY() {
        int d = Win.mouseDY + dy;
        Win.mouseDY = 0;
        dy = 0;
        return d;
    }

    public static int getDWheel() {
        int d = Win.mouseDWheel;
        Win.mouseDWheel = 0;
        return d;
    }

    public static boolean isButtonDown(int button) {
        return button >= 0 && button < Win.mouseButtons.length && Win.mouseButtons[button];
    }

    public static boolean isInsideWindow() {
        return Win.mouseInside;
    }

    public static void setCursorPosition(int x, int y) {
        if (!Win.isCreated()) {
            return;
        }
        Win.mouseX = x;
        Win.mouseY = y;
        // Converts back to GLFW window coordinates.
        double wx = x * (Win.windowWidth / (double) Math.max(1, Win.width));
        double wy = Input.flipY(y) * (Win.windowHeight / (double) Math.max(1, Win.height));
        glfwSetCursorPos(Win.handle, wx, wy);
        if (Win.grabbed) {
            releaseX = wx;
            releaseY = wy;
        }
    }

    /**
     * Captured mode: the cursor disappears and movement becomes unlimited — it is what the game
     * uses to look around.
     */
    public static void setGrabbed(boolean grab) {
        if (!Win.isCreated() || grab == Win.grabbed) {
            return;
        }
        Win.grabbed = grab;
        glfwSetInputMode(Win.handle, GLFW_CURSOR, grab ? GLFW_CURSOR_DISABLED : GLFW_CURSOR_NORMAL);
        if (!grab && !Double.isNaN(releaseX)) {
            // On release, GLFW puts the cursor back where it was when it was captured; in LWJGL 2
            // it stays where it was requested. The game centers it before releasing
            // (MouseHelper.ungrabMouseCursor), so without this the inventory opened with the
            // cursor where the last screen had been closed.
            glfwSetCursorPos(Win.handle, releaseX, releaseY);
        }
        releaseX = Double.NaN;
        // Discards the position jump generated by the mode switch itself.
        Win.mouseDX = 0;
        Win.mouseDY = 0;
        double[] x = new double[1];
        double[] y = new double[1];
        glfwGetCursorPos(Win.handle, x, y);
        Win.mouseX = (int) x[0];
        Win.mouseY = Input.flipY((int) y[0]);
    }

    public static boolean isGrabbed() {
        return Win.grabbed;
    }
}
